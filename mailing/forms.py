_LEADING = re.compile(r"^[\s«\"“<(]+")
_PUNCTUATION = re.compile(r"[\s\-–—()]+")


def _plain(text: str) -> str:
    """Название -> строка для сравнения: без кавычек в начале, строчными, ё как е, дефисы и скобки как пробелы."""
    return _PUNCTUATION.sub(" ", _LEADING.sub("", text).casefold().replace("ё", "е")).strip()


_FULL_BY_LENGTH = sorted(((_plain(full), form) for form, names in FULL_NAMES.items() for full in names),
                         key=lambda item: -len(item[0]))


def _form_by_full_name(name: str) -> Optional[str]:
    plain = _plain(name)
    for full, form in _FULL_BY_LENGTH:
        if plain.startswith(full) and not plain[len(full):len(full) + 1].isalpha():
            return form
    return None


def org_form(name, known=KNOWN_FORMS, full_names=True):
    """Название компании -> форма организации: «ООО "ТЕККИН"» -> «ООО», «МБУ МП "КЦМИ"» -> «МБУ»; не из известных ->
    «другая»; колонки с названием нет (None) -> None, форма не проверяется. Название нигде не сохраняется.

    known - сокращения, которые считаются формой (по умолчанию KNOWN_FORMS; страница /leads добавляет формы из таблицы
    владельца). full_names - узнавать и полное название («Товарищество собственников недвижимости» -> «ТСН»); выключено,
    узнаётся только полное название ООО, как было в compose.py до таблицы полных названий."""
    if name is None:
        return None
    if _FULL_OOO.match(name):
        return "ООО"
    found = _FORM_WORD.match(name)
    if found and found.group(1) in known:
        return found.group(1)
    return (_form_by_full_name(name) if full_names else None) or OTHER_FORM


def read_form_rules(path: str) -> dict:
    """Файл okved-map.md -> {форма: писать (True) или не писать (False)}. OSError - файл не открылся, ComposeError или
    ValueError - в разделе «Формы» непонятное решение или файл не в UTF-8."""
    with open(path, encoding="utf-8-sig") as fh:
        return parse_form_rules(fh.read())


class FormFilter:
    """Правила форм на один запуск выгрузки. rules - {форма: писать?} либо None, если правил нет: тогда фильтр отключён,
    problem - строка для журнала, notice - предупреждение для страницы."""

    def __init__(self, rules: Optional[dict] = None, problem: str = "", notice: str = ""):
        self.rules, self.problem, self.notice = rules, problem, notice

    @property
    def active(self) -> bool:
        return self.rules is not None

    def form_of(self, name):
        """Форма по названию; формы из таблицы владельца считаются известными, даже если их нет в KNOWN_FORMS."""
        return org_form(name, KNOWN_FORMS | self.rules.keys() if self.rules else KNOWN_FORMS)

    def blocked(self, form) -> bool:
        """Владелец решил не писать этой форме. «Другая» форма, отсутствие названия и форма без решения не пропускаются."""
        return bool(self.rules) and form not in (None, OTHER_FORM) and self.rules.get(form) is False

    def blocked_forms(self) -> list:
        return sorted(form for form, write in (self.rules or {}).items() if not write)

    def describe(self) -> str:
        """Строка журнала о том, что прочитано: какие формы сейчас «не писать» (названия форм, не компаний)."""
        blocked = self.blocked_forms()
        return ("Правила форм прочитаны: не писать - " + ", ".join(blocked)) if blocked \
            else "Правила форм прочитаны: форм «не писать» нет"


def load_filter(path: str) -> FormFilter:
    """Правила форм из файла по пути (OUTREACH_OKVED_MAP). Читается при каждом вызове: строка, которую владелец добавил в
    таблицу «Формы», действует без перезапуска сайта. Путь не задан или файла нет - фильтр отключён."""
    path = (path or "").strip()
    if not path or not os.path.isfile(path):
        return FormFilter(None, "правила форм не найдены: фильтр отключён (укажите OUTREACH_OKVED_MAP)",
                          "правила форм не найдены, фильтр отключён")
    try:
        return FormFilter(read_form_rules(path))
    except (OSError, ComposeError, ValueError) as exc:
        reason = (exc.strerror if isinstance(exc, OSError) else str(exc)) or exc.__class__.__name__
        return FormFilter(None, f"правила форм не прочитаны: фильтр отключён ({reason})",
                          f"правила форм не прочитаны, фильтр отключён ({reason})")
